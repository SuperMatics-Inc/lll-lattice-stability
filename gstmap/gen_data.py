"""Exact (Fraction) validation of tree.jsonl and generation of lean/GSTMap/Data.lean.

Validation (independent of the Arb engine; pure rational arithmetic):
  * every internal node (ev=split) has its four children present, every leaf carries exactly one of K/S/U/X;
  * leaves of each of the 76 root cells tile the root exactly (area sum), no duplicates, all dyadic;
  * every K leaf satisfies (c1+w)^2+(c2+w)^2 < 1;
  * statistics per kind, area per kind.
Usage: python gen_data.py tree.jsonl lean/GSTMap/Data.lean
"""
import json, sys
from fractions import Fraction as F
from collections import Counter, defaultdict


def load(path):
    nodes = {}
    for ln in open(path):
        ln = ln.strip()
        if not ln:
            continue
        e = json.loads(ln)
        k = (F(e["c1"]), F(e["c2"]), F(e["w"]))
        if k in nodes and nodes[k]["ev"] != e["ev"]:
            # a node may be re-run (X re-run, resume): keep the most decisive (S/U over X over split? keep last)
            pass
        nodes[k] = e
    return nodes


KIND = {"K": "skip", "S": "stab", "U": "unst", "X": "undec"}


def build(nodes, root, errors):
    c1, c2, w = root
    e = nodes.get(root)
    if e is None:
        errors.append(("missing", root))
        return ("leaf", "undec"), [(("X"), root)]
    if e["ev"] == "split":
        h = w / 2
        ch = [(c1 + a * h, c2 + b * h, h) for a in (-1, 1) for b in (-1, 1)]
        subs = [build(nodes, c, errors) for c in ch]
        leaves = [l for s in subs for l in s[1]]
        return ("split", [s[0] for s in subs]), leaves
    if e["ev"] == "err":
        errors.append(("err", root))
        return ("leaf", "undec"), [("X", root)]
    return ("leaf", KIND[e["ev"]]), [(e["ev"], root)]


def lean_term(t):
    if t[0] == "leaf":
        return f"(.leaf .{t[1]})"
    return "(.split " + " ".join(lean_term(s) for s in t[1]) + ")"


def main(src, dst):
    nodes = load(src)
    errors = []
    roots = [(F(1, 16) + F(k, 8), F(7 + j, 8), F(1, 16)) for k in range(4) for j in range(19)]
    trees = []
    all_leaves = []
    for r in roots:
        t, lv = build(nodes, r, errors)
        trees.append(t)
        all_leaves.extend(lv)
        area = sum((4 * l[1][2] ** 2) for l in lv)
        assert area == 4 * r[2] ** 2, ("area mismatch", r, area)
    # duplicates
    seen = Counter(l[1] for l in all_leaves)
    dup = [k for k, v in seen.items() if v > 1]
    assert not dup, dup
    kinds = Counter(l[0] for l in all_leaves)
    area = defaultdict(F)
    for kd, (c1, c2, w) in all_leaves:
        area[kd] += 4 * w * w
        if kd == "K":
            assert (c1 + w) ** 2 + (c2 + w) ** 2 < 1, ("skip violated", c1, c2, w)
    # every cell used in the tree appears in the file (no orphans of other runs): count unused nodes
    used = set(l[1] for l in all_leaves)
    stats = dict(leaves=len(all_leaves), kinds=dict(kinds), area={k: str(v) for k, v in area.items()},
                 area_float={k: float(v) for k, v in area.items()}, errors=len(errors), total_area=str(sum(area.values())))
    print(json.dumps(stats))
    if errors:
        print("ERRORS", errors[:10])
        sys.exit(2)
    out = ["import GSTMap.Tree", "", "/-! Generated by gen_data.py from the tree.jsonl produced by tree.py. DO NOT EDIT. -/", "",
           "namespace GSTMap", ""]
    for i, t in enumerate(trees):
        out.append(f"def tr{i} : QT := {lean_term(t)}")
    out.append("")
    out.append("/-- the 76 root quadtrees, index `19*k + j` for column `k<4`, row `j<19`. -/")
    out.append("def forestList : List QT := [" + ", ".join(f"tr{i}" for i in range(len(trees))) + "]")
    out.append("def forest (k j : ℕ) : QT := forestList.getD (19 * k + j) (.leaf .undec)")
    out.append("")
    out.append("theorem forest_skip_ok : ∀ k : Fin 4, ∀ j : Fin 19,")
    out.append("    (forest k j).skipOK (rootCell k j) = true := by decide +kernel")
    out.append("theorem skip_ok : ∀ kc ∈ allLeaves forest, kc.1 = Kind.skip →")
    out.append("    (kc.2.x + kc.2.h) ^ 2 + (kc.2.y + kc.2.h) ^ 2 < 1 := by")
    out.append("  intro kc hk hks")
    out.append("  simp only [allLeaves, List.mem_flatMap, List.mem_range] at hk")
    out.append("  obtain ⟨k,hk,j,hj,hkc⟩ := hk")
    out.append("  exact (forest k j).skipOK_correct _ (forest_skip_ok ⟨k,hk⟩ ⟨j,hj⟩) kc hkc hks")
    for nm, kn in (("skip", "skip"), ("stab", "stab"), ("unst", "unst"), ("undec", "undec")):
        c = kinds[{"skip": "K", "stab": "S", "unst": "U", "undec": "X"}[kn]]
        out.append(f"theorem structural_count_{nm} : forestCount forest Kind.{kn} = {c} := by decide +kernel")
        out.append(f"theorem count_{nm} : ((allLeaves forest).filter (fun kc => kc.1 == Kind.{kn})).length = {c} := by")
        out.append(f"  rw [allLeaves_count, structural_count_{nm}]")
    out.append(f"theorem count_all : (allLeaves forest).length = {len(all_leaves)} := by")
    out.append("  have hs := count_skip; have ht := count_stab; have hu := count_unst; have hx := count_undec")
    out.append("  have hh : ∀ l : List (Kind × RCell), l.length =")
    out.append("      (l.filter (fun kc => kc.1 == Kind.skip)).length +")
    out.append("      (l.filter (fun kc => kc.1 == Kind.stab)).length +")
    out.append("      (l.filter (fun kc => kc.1 == Kind.unst)).length +")
    out.append("      (l.filter (fun kc => kc.1 == Kind.undec)).length := by")
    out.append("    intro l; induction l with")
    out.append("    | nil => simp")
    out.append("    | cons a l ih =>")
    out.append("      rcases a with ⟨k,c⟩")
    out.append("      cases k <;> simp_all <;> omega")
    out.append("  have := hh (allLeaves forest)")
    out.append("  omega")
    out.append("")
    out.append("end GSTMap")
    open(dst, "w", encoding="utf-8").write("\n".join(out) + "\n")
    print("wrote", dst, "bytes", sum(len(x) + 1 for x in out))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
